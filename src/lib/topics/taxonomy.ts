/**
 * NEURA PHASE 7 — Topic Taxonomy Utilities
 *
 * Deterministic slug normalizer and server-side topic upsert helper.
 *
 * Rules (applied in order):
 *  1. Lowercase and trim.
 *  2. Strip all characters that are not alphanumeric or whitespace.
 *  3. Collapse one or more whitespace characters into a single underscore.
 *  4. Strip leading/trailing underscores that remain after step 3.
 *
 * Examples:
 *   "Photosynthesis"        → "photosynthesis"
 *   "Newton's Laws"         → "newtons_laws"
 *   "  Cell   Division  "   → "cell_division"
 *   "DNA & RNA (Basics)"    → "dna_rna_basics"
 *
 * The normalizer is pure (no I/O) so it can be imported in tests without
 * mocking anything.
 */

// ---------------------------------------------------------------------------
// Pure slug normalizer
// ---------------------------------------------------------------------------

/**
 * Converts any free-form topic string into a stable, URL-safe slug.
 * Identical to the regexp used in the Postgres backfill step so that slugs
 * generated by TypeScript always match rows created by the migration.
 *
 * Returns an empty string only if the input is blank after stripping.
 */
export function normalizeTopicSlug(raw: string): string {
  return raw
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9\s]/g, "")  // strip punctuation
    .replace(/\s+/g, "_")          // collapse whitespace → underscore
    .replace(/^_+|_+$/g, "");      // strip leading/trailing underscores
}

/**
 * Returns true if the slug is non-empty and consists only of valid characters
 * after normalization. Used to guard against blank or degenerate topic strings.
 */
export function isValidTopicSlug(slug: string): boolean {
  return slug.length > 0 && /^[a-z0-9][a-z0-9_]*[a-z0-9]$|^[a-z0-9]$/.test(slug);
}

// ---------------------------------------------------------------------------
// Server-side topic upsert (called from Route Handlers — never from the browser)
// ---------------------------------------------------------------------------

export interface TopicRecord {
  id: string;
  name: string;
  subject: string;
  slug: string;
}

/**
 * Resolves a topic from the database using its slug, upserting it if it does
 * not already exist.
 *
 * - Uses INSERT … ON CONFLICT (slug) DO NOTHING + SELECT to avoid race
 *   conditions on concurrent requests for the same topic.
 * - The Supabase client passed in MUST be a server-side (anon or service-role)
 *   client — never a browser client. The caller is responsible for passing
 *   the right client.
 * - Returns null if the slug is invalid (prevents junk rows entering the taxonomy).
 *
 * @param supabase   Server-side Supabase client (from createClient() or createAdminClient())
 * @param topicName  Free-form topic name as submitted by the user/AI ("Photosynthesis")
 * @param subject    Subject area ("Biology", "Maths" — free text, not validated here)
 */
export async function upsertTopic(
  supabase: NonNullable<Awaited<ReturnType<typeof import("@/lib/supabase/server").createClient>>>,
  topicName: string,
  subject: string
): Promise<TopicRecord | null> {
  const slug = normalizeTopicSlug(topicName);
  if (!isValidTopicSlug(slug)) {
    return null;
  }

  // Try a direct SELECT first (fast path — topic likely already exists).
  const { data: existing } = await supabase
    .from("topics")
    .select("id, name, subject, slug")
    .eq("slug", slug)
    .maybeSingle();

  if (existing) {
    return existing as TopicRecord;
  }

  // Not found — insert and then select (INSERT … ON CONFLICT DO NOTHING handles
  // the race case where another request inserts between our SELECT and INSERT).
  await supabase
    .from("topics")
    .insert({ name: topicName.trim(), subject: subject.trim(), slug })
    .throwOnError();

  const { data: inserted } = await supabase
    .from("topics")
    .select("id, name, subject, slug")
    .eq("slug", slug)
    .maybeSingle();

  return (inserted as TopicRecord | null) ?? null;
}
